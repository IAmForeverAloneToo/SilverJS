"""Generates SilverJS's simple case folding table
(src/regexp/casefold_tables.rs) from the Unicode Character Database, for
the `i` flag with `u` or `v` (Canonicalize, section 22.2.2.7.3).

    python -I tools/gen_casefold.py <ucd dir> src/regexp/casefold_tables.rs

<ucd dir> is the ucd/ directory of UCD_VERSION
(https://www.unicode.org/Public/<version>/ucd/): CaseFolding.txt is read,
its common (C) and simple (S) mappings. The version is the one the
reference browser ships (Chrome 158: Unicode 17.0.0, the J4.4d probe),
the same for every generated table; the input must be of that version,
and the output records the version and its SHA-256. The output is
checked in; a new version means changing UCD_VERSION here and in the
other generators and running them again, in a commit of its own.
"""

import hashlib
import os
import re
import sys

UCD_VERSION = "17.0.0"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    ucd, target = sys.argv[1], sys.argv[2]
    name = "CaseFolding.txt"
    path = os.path.join(ucd, name)
    version = None
    folds = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.search(r"-(\d+\.\d+\.\d+)\.txt", line)
                if m:
                    version = m.group(1)
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            fields = [x.strip() for x in body.split(";")]
            if fields[1] in ("C", "S"):
                folds.append((int(fields[0], 16), int(fields[2], 16)))
    if version != UCD_VERSION:
        sys.exit(f"the file is not of UCD {UCD_VERSION}: {version}")
    with open(path, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    folds.sort()
    parts = [
        "// Generated by tools/gen_casefold.py from the Unicode Character",
        f"// Database {UCD_VERSION}. Do not edit: run the generator again.",
        "// Inputs (SHA-256):",
        f"//   {digest}  {name}",
        "",
        "/// Simple case folding (statuses C and S): each code point that folds,",
        "/// and what it folds to, sorted.",
        "pub(crate) const SIMPLE_FOLD: &[(u32, u32)] = &[",
    ]
    parts += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in folds]
    parts += ["];", ""]
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
