"""Generates the property names RegExp's \\p{...} accepts
(src/regexp/properties.rs) from the Unicode Character Database.

    python -I tools/gen_properties.py <PropertyValueAliases.txt> src/regexp/properties.rs

The file is that of UCD_VERSION
(https://www.unicode.org/Public/<version>/ucd/), the version the
reference browser ships and every generated table uses (Chrome 158:
Unicode 17.0.0, the J4.4d probe); it must say it is of that version, and
the output records the version and its SHA-256. General_Category and
Script values
come from it, every alias of each; the binary properties and the
properties of strings are ECMA-262's own lists (section 22.2.2.9's
tables). The output is checked in; run this again with the UCD's next
version, in a commit of its own.
"""

import hashlib
import re
import sys

UCD_VERSION = "17.0.0"

# ECMA-262's table of binary Unicode property aliases: canonical name
# and short alias.
BINARY = [
    ("ASCII", None), ("ASCII_Hex_Digit", "AHex"), ("Alphabetic", "Alpha"),
    ("Any", None), ("Assigned", None), ("Bidi_Control", "Bidi_C"),
    ("Bidi_Mirrored", "Bidi_M"), ("Case_Ignorable", "CI"), ("Cased", None),
    ("Changes_When_Casefolded", "CWCF"), ("Changes_When_Casemapped", "CWCM"),
    ("Changes_When_Lowercased", "CWL"), ("Changes_When_NFKC_Casefolded", "CWKCF"),
    ("Changes_When_Titlecased", "CWT"), ("Changes_When_Uppercased", "CWU"),
    ("Dash", None), ("Default_Ignorable_Code_Point", "DI"), ("Deprecated", "Dep"),
    ("Diacritic", "Dia"), ("Emoji", None), ("Emoji_Component", "EComp"),
    ("Emoji_Modifier", "EMod"), ("Emoji_Modifier_Base", "EBase"),
    ("Emoji_Presentation", "EPres"), ("Extended_Pictographic", "ExtPict"),
    ("Extender", "Ext"), ("Grapheme_Base", "Gr_Base"), ("Grapheme_Extend", "Gr_Ext"),
    ("Hex_Digit", "Hex"), ("IDS_Binary_Operator", "IDSB"),
    ("IDS_Trinary_Operator", "IDST"), ("ID_Continue", "IDC"), ("ID_Start", "IDS"),
    ("Ideographic", "Ideo"), ("Join_Control", "Join_C"),
    ("Logical_Order_Exception", "LOE"), ("Lowercase", "Lower"), ("Math", None),
    ("Noncharacter_Code_Point", "NChar"), ("Pattern_Syntax", "Pat_Syn"),
    ("Pattern_White_Space", "Pat_WS"), ("Quotation_Mark", "QMark"), ("Radical", None),
    ("Regional_Indicator", "RI"), ("Sentence_Terminal", "STerm"),
    ("Soft_Dotted", "SD"), ("Terminal_Punctuation", "Term"),
    ("Unified_Ideograph", "UIdeo"), ("Uppercase", "Upper"),
    ("Variation_Selector", "VS"), ("White_Space", "space"),
    ("XID_Continue", "XIDC"), ("XID_Start", "XIDS"),
]

# ECMA-262's table of binary Unicode properties of strings (`v` only).
STRINGS = [
    "Basic_Emoji", "Emoji_Keycap_Sequence", "RGI_Emoji_Modifier_Sequence",
    "RGI_Emoji_Flag_Sequence", "RGI_Emoji_Tag_Sequence",
    "RGI_Emoji_ZWJ_Sequence", "RGI_Emoji",
]


def values(path, prop):
    """Every alias of every value of `prop` (gc or sc), and the UCD
    version."""
    names = set()
    version = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.search(r"-(\d+\.\d+\.\d+)\.txt", line)
                if m:
                    version = m.group(1)
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            if fields[0] != prop:
                continue
            names.update(x for x in fields[1:] if x and x != "n/a")
    return sorted(names), version


def emit(name, items):
    out = [f"pub(super) const {name}: &[&str] = &["]
    out += [f'    "{x}",' for x in items]
    out.append("];")
    return "\n".join(out)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    gc, version = values(src, "gc")
    sc, _ = values(src, "sc")
    if version != UCD_VERSION:
        sys.exit(f"the file is not of UCD {UCD_VERSION}: {version}")
    with open(src, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    binary = sorted({n for pair in BINARY for n in pair if n})
    text = "\n\n".join([
        "//! The names RegExp's `\\p{...}` accepts: generated by\n"
        f"//! tools/gen_properties.py from UCD {version}'s PropertyValueAliases.txt\n"
        f"//! (SHA-256 {digest})\n"
        "//! and ECMA-262's tables. Do not edit.",
        emit("GENERAL_CATEGORY", gc),
        emit("SCRIPT", sc),
        emit("BINARY", binary),
        emit("STRINGS", sorted(STRINGS)),
        """/// A name alone: a General_Category value or a binary property.
pub(super) fn lone_name(name: &str) -> bool {
    GENERAL_CATEGORY.binary_search(&name).is_ok() || BINARY.binary_search(&name).is_ok()
}

/// `Name=Value`: General_Category, Script or Script_Extensions.
pub(super) fn valid_value(name: &str, value: &str) -> bool {
    match name {
        "General_Category" | "gc" => GENERAL_CATEGORY.binary_search(&value).is_ok(),
        "Script" | "sc" | "Script_Extensions" | "scx" => SCRIPT.binary_search(&value).is_ok(),
        _ => false,
    }
}

/// A property of strings (`v` mode only).
pub(super) fn string_property(name: &str) -> bool {
    STRINGS.binary_search(&name).is_ok()
}""",
    ])
    with open(dst, "w", encoding="ascii", newline="\n") as f:
        f.write(text + "\n")


main()
