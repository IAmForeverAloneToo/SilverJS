"""Generates SilverJS's Unicode tables (src/unicode_tables.rs) from the
Unicode Character Database.

    python -I tools/gen_unicode.py <ucd dir> src/unicode_tables.rs

<ucd dir> holds DerivedCoreProperties.txt and DerivedGeneralCategory.txt
of one UCD version (https://www.unicode.org/Public/UCD/latest/ucd/, the
second under extracted/). The output is checked in; the generator is run
again when the UCD moves to a new version, in a commit of its own.

The tables list only code points from U+0080 up: the lexer answers ASCII
itself.
"""

import re
import sys

LINE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")


def read(path, wanted):
    """The ranges of each property of `wanted` in a UCD file, merged and
    sorted, and the file's version."""
    ranges = {name: [] for name in wanted}
    version = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.search(r"-(\d+\.\d+\.\d+)\.txt", line)
                if m:
                    version = m.group(1)
            m = LINE.match(line)
            if not m or m.group(3) not in ranges:
                continue
            lo = int(m.group(1), 16)
            hi = int(m.group(2), 16) if m.group(2) else lo
            ranges[m.group(3)].append((lo, hi))
    for name, found in ranges.items():
        found.sort()
        merged = []
        for lo, hi in found:
            if merged and lo <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
            else:
                merged.append((lo, hi))
        ranges[name] = [(lo, hi) for lo, hi in merged if hi >= 0x80]
        ranges[name] = [(max(lo, 0x80), hi) for lo, hi in ranges[name]]
    return ranges, version


def table(name, doc, ranges):
    out = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    for lo, hi in ranges:
        out.append(f"    (0x{lo:04X}, 0x{hi:04X}),")
    out.append("];")
    return "\n".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    ucd, target = sys.argv[1], sys.argv[2]
    core, v1 = read(f"{ucd}/DerivedCoreProperties.txt", ["ID_Start", "ID_Continue"])
    cats, v2 = read(f"{ucd}/DerivedGeneralCategory.txt", ["Zs"])
    if v1 != v2 or v1 is None:
        sys.exit(f"the files are of different or unknown versions: {v1}, {v2}")
    parts = [
        "// Generated by tools/gen_unicode.py from the Unicode Character",
        f"// Database {v1}. Do not edit: run the generator again.",
        "",
        "/// The Unicode version of these tables.",
        f'pub const UNICODE_VERSION: &str = "{v1}";',
        "",
        table("ID_START", "`ID_Start` from U+0080 up, as inclusive ranges.", core["ID_Start"]),
        "",
        table(
            "ID_CONTINUE",
            "`ID_Continue` from U+0080 up, as inclusive ranges.",
            core["ID_Continue"],
        ),
        "",
        table("SPACE_SEPARATOR", "General category `Zs` from U+0080 up.", cats["Zs"]),
        "",
    ]
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
