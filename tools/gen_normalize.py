"""Generates SilverJS's normalization tables (src/normalize_tables.rs)
from the Unicode Character Database, for String.prototype.normalize.

    python -I tools/gen_normalize.py <ucd dir> src/normalize_tables.rs

<ucd dir> is the ucd/ directory of UCD_VERSION
(https://www.unicode.org/Public/<version>/ucd/): UnicodeData.txt and
DerivedNormalizationProps.txt are read. The version is the one the
reference browser ships (Chrome 158: Unicode 17.0.0, the J4.4d probe),
the same for every generated table; each input must be of that version,
and the output records the version and each input's SHA-256. The output
is checked in; a new version means changing UCD_VERSION here and in the
other generators and running them again, in a commit of its own.

The tables (UAX #15): each code point's Canonical_Combining_Class when
not 0; each one's decomposition mapping, one level (applied again at run
time), marked when it is a compatibility one; and the canonical pairs
that compose, those of two-code-point canonical mappings less
Full_Composition_Exclusion. Hangul syllables are left to the algorithm.
"""

import hashlib
import os
import re
import sys

UCD_VERSION = "17.0.0"


def version_of(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.search(r"-(\d+\.\d+\.\d+)\.txt", line)
            if m:
                return m.group(1)
    return None


def unicode_data(path):
    """Combining classes and decomposition mappings."""
    ccc, decomp = {}, {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.rstrip("\n").split(";")
            if len(fields) < 6:
                continue
            cp = int(fields[0], 16)
            if fields[3] != "0":
                ccc[cp] = int(fields[3])
            d = fields[5].strip()
            if d:
                compat = d.startswith("<")
                if compat:
                    d = d.split(">", 1)[1].strip()
                decomp[cp] = (compat, [int(x, 16) for x in d.split()])
    return ccc, decomp


def exclusions(path):
    """Full_Composition_Exclusion."""
    out = set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            if len(fields) < 2 or fields[1] != "Full_Composition_Exclusion":
                continue
            lo, _, hi = fields[0].partition("..")
            for cp in range(int(lo, 16), int(hi or lo, 16) + 1):
                out.add(cp)
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    ucd, target = sys.argv[1], sys.argv[2]
    inputs = ["UnicodeData.txt", "DerivedNormalizationProps.txt"]
    # UnicodeData.txt names no version of its own; its sibling does.
    v = version_of(os.path.join(ucd, inputs[1]))
    if v != UCD_VERSION:
        sys.exit(f"the files are not of UCD {UCD_VERSION}: {v}")
    ccc, decomp = unicode_data(os.path.join(ucd, inputs[0]))
    excluded = exclusions(os.path.join(ucd, inputs[1]))
    compose = sorted(
        (m[0], m[1], cp)
        for cp, (compat, m) in decomp.items()
        if not compat and len(m) == 2 and cp not in excluded
    )
    parts = [
        "// Generated by tools/gen_normalize.py from the Unicode Character",
        f"// Database {UCD_VERSION}. Do not edit: run the generator again.",
        "// Inputs (SHA-256):",
    ]
    for name in inputs:
        with open(os.path.join(ucd, name), "rb") as f:
            parts.append(f"//   {hashlib.sha256(f.read()).hexdigest()}  {name}")
    parts += [
        "",
        "/// Each code point's Canonical_Combining_Class, where not 0.",
        "pub(crate) const COMBINING_CLASS: &[(u32, u8)] = &[",
    ]
    parts += [f"    (0x{cp:04X}, {c})," for cp, c in sorted(ccc.items())]
    parts += [
        "];",
        "",
        "/// Each decomposition mapping, one level: the code point, where its",
        "/// mapping starts in [`DECOMPOSITION_DATA`] and how long it is, and",
        "/// whether it is a compatibility mapping.",
        "pub(crate) const DECOMPOSITION: &[(u32, u16, u8, bool)] = &[",
    ]
    data = []
    for cp, (compat, m) in sorted(decomp.items()):
        parts.append(f"    (0x{cp:04X}, {len(data)}, {len(m)}, {str(compat).lower()}),")
        data += m
    parts += ["];", "", "/// The mappings' code points.", "pub(crate) const DECOMPOSITION_DATA: &[u32] = &["]
    for i in range(0, len(data), 8):
        parts.append("    " + " ".join(f"0x{x:04X}," for x in data[i:i + 8]))
    parts += [
        "];",
        "",
        "/// The canonical pairs that compose (first, second, composite),",
        "/// sorted by the pair.",
        "pub(crate) const COMPOSITION: &[(u32, u32, u32)] = &[",
    ]
    parts += [f"    (0x{a:04X}, 0x{b:04X}, 0x{c:04X})," for a, b, c in compose]
    parts += ["];", ""]
    assert len(data) < 65536
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
